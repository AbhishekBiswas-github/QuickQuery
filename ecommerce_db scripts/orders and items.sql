USE ecommerce_db;

-- -----------------------------------------------------------
-- TABLE 5: orders
-- -----------------------------------------------------------
CREATE TABLE IF NOT EXISTS orders (
    order_id            INT           UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    customer_id         INT           UNSIGNED NOT NULL,
    shipping_address_id INT           UNSIGNED NOT NULL,
    billing_address_id  INT           UNSIGNED NOT NULL,
    order_number        VARCHAR(30)   NOT NULL UNIQUE,
    status              ENUM('pending','confirmed','processing','shipped',
                             'delivered','cancelled','refunded','on_hold')
                                      NOT NULL DEFAULT 'pending',
    payment_status      ENUM('unpaid','paid','partially_paid','refunded','failed')
                                      NOT NULL DEFAULT 'unpaid',
    payment_method      ENUM('credit_card','debit_card','paypal',
                             'apple_pay','google_pay','bank_transfer','cod')
                                      NOT NULL DEFAULT 'credit_card',
    subtotal            DECIMAL(12,2) NOT NULL,
    discount_amount     DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    shipping_cost       DECIMAL(8,2)  NOT NULL DEFAULT 0.00,
    tax_amount          DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    total_amount        DECIMAL(12,2) NOT NULL,
    coupon_code         VARCHAR(30)   DEFAULT NULL,
    notes               TEXT          DEFAULT NULL,
    shipped_at          DATETIME      DEFAULT NULL,
    delivered_at        DATETIME      DEFAULT NULL,
    cancelled_at        DATETIME      DEFAULT NULL,
    created_at          DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT fk_order_customer
        FOREIGN KEY (customer_id)         REFERENCES customers (customer_id)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_order_ship_addr
        FOREIGN KEY (shipping_address_id) REFERENCES addresses (address_id)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_order_bill_addr
        FOREIGN KEY (billing_address_id)  REFERENCES addresses (address_id)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    INDEX idx_customer     (customer_id),
    INDEX idx_status       (status),
    INDEX idx_pay_status   (payment_status),
    INDEX idx_created      (created_at),
    INDEX idx_order_number (order_number)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -----------------------------------------------------------
-- TABLE 6: order_items
-- -----------------------------------------------------------
CREATE TABLE IF NOT EXISTS order_items (
    order_item_id  INT           UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    order_id       INT           UNSIGNED NOT NULL,
    product_id     INT           UNSIGNED NOT NULL,
    sku_snapshot   VARCHAR(60)   NOT NULL  COMMENT 'SKU at time of purchase',
    name_snapshot  VARCHAR(200)  NOT NULL  COMMENT 'Product name at time of purchase',
    unit_price     DECIMAL(10,2) NOT NULL,
    quantity       INT           UNSIGNED NOT NULL DEFAULT 1,
    discount_pct   DECIMAL(5,2)  NOT NULL DEFAULT 0.00,
    line_total     DECIMAL(12,2) NOT NULL,
    CONSTRAINT fk_item_order
        FOREIGN KEY (order_id)   REFERENCES orders   (order_id)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_item_product
        FOREIGN KEY (product_id) REFERENCES products (product_id)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    INDEX idx_order   (order_id),
    INDEX idx_product (product_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

